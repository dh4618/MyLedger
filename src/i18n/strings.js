// The language list drives the picker. `label` is always written in its own
// language — a language name should never be translated.
// `locale` is what Intl.DateTimeFormat receives, which is why en uses en-GB:
// the app's dates read "Thursday, 30 July", not "July 30".
export const LANGUAGES = [
  { id: 'en', label: 'English', locale: 'en-GB', strings: en },
  { id: 'zh-CN', label: '简体中文', locale: 'zh-CN', strings: zhCN },
];

export const LANGUAGE_IDS = LANGUAGES.map((l) => l.id);
export const DEFAULT_LANGUAGE_ID = 'en';
