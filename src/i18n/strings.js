// ---------------------------------------------------------------------------
// Interface strings, one object per language.
//
// Deliberately a plain dictionary rather than an i18n library. For two languages
// and ~150 keys, i18next and friends are more machinery than the problem needs,
// and this app ships a service worker and is expected to work offline — every
// avoided dependency is bytes the cache doesn't have to carry.
//
// Conventions:
//   - Keys are dot-namespaced by area. Add to both languages together; the key
//     parity check in the verification script fails the build otherwise.
//   - {name} placeholders are substituted by t() in LanguageProvider.jsx.
//   - Nothing here is ever persisted, so switching language retranslates the
//     whole interface with no migration. Goal and task names are user input and
//     are never translated.
//   - No plurals anywhere, on purpose: Chinese has no plural forms, and every
//     English string is phrased to avoid needing one.
// ---------------------------------------------------------------------------

