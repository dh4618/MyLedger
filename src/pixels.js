// Pixel art for the four creatures, four growth stages each, two frames apiece.
//
// Each sprite is a palette plus one string per row, where a character indexes the
// palette and '.' is transparent. `alt` is the second frame against the same palette:
// eyes closed for anything with eyes, and for an egg — which has none — the whole
// shape nudged a pixel, so it wobbles. Kept as data rather than markup so the whole
// set costs a few KB, renders crisp at any size through <Pixel>, and a redraw
// replaces this one file.
//
// Generated from 32 transparent 24x24 PNGs, one per frame. Three properties of that
// source are load-bearing, and a redraw should keep all three:
//
//   - One canvas size for everything. The frames of a pair stack exactly, which is
//     what lets the blink be one sprite drawn over another rather than a swap, and
//     it keeps the stages at their true relative sizes: a kid is smaller than an
//     adult because it is drawn smaller, not because <Pixel> was told a number.
//   - Bottom-aligned. Every creature stands on the canvas's last row, so a sprite
//     placed in the room stands on the floor whatever shape it is.
//   - A real alpha channel. The first set of these was recovered from a flat sheet,
//     where transparency had to be guessed by flood-filling from outside each sprite
//     — deciding it by colour got the frog's eyes, the cat's muzzle and Inky's page
//     wrong, since those are white paint rather than holes, which is invisible on a
//     light background and obvious on a dark one. With alpha there is nothing to
//     guess.

