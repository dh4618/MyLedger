export const SPECIES_IDS = Object.keys(SPRITES);
export const STAGES = ['egg', 'kid', 'young', 'adult'];

// Shown before a generic egg is opened, and as the app's face before anything is
// hatched. Deliberately the plainest of the four eggs so it reads as "unknown".
export const MYSTERY_EGG = SPRITES.inky.egg;

export const spriteFor = (species, stage) => {
  const s = SPRITES[species];
  if (!s) return MYSTERY_EGG;
  return s[stage] || s.egg;
};
